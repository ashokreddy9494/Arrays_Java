package strings.string_class_methods;
//It is due to String are immutable / so that we have to store it in a variable
public class ToUpperCaseMethod {
    public static void main(String[] args) {
        String s1 = "ee sala cup namde";

        System.out.println(s1.toUpperCase()); //EE SALA CUP NAMDE
        System.out.println(s1); //ee sala cup namde
    }
}
